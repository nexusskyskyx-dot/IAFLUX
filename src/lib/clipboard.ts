/**
 * Copy text to the clipboard, returning whether it succeeded.
 *
 * `navigator.clipboard` is undefined outside a secure context, so a plain-HTTP
 * self-hosted instance needs the legacy path; it is also unavailable in some
 * embedded browsers. Callers show a toast, so never throw.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  if (typeof navigator !== 'undefined' && navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Permission denied or blocked — try the legacy path below.
    }
  }
  try {
    const area = document.createElement('textarea');
    area.value = text;
    area.setAttribute('readonly', '');
    area.style.position = 'fixed';
    area.style.top = '0';
    area.style.opacity = '0';
    document.body.appendChild(area);
    area.select();
    const copied = document.execCommand('copy');
    area.remove();
    return copied;
  } catch {
    return false;
  }
}
